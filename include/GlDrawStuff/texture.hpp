#ifndef GL_DRAW_STUFF_TEXTURE_HPP
#define GL_DRAW_STUFF_TEXTURE_HPP

#include <iostream>

#define STB_IMAGE_IMPLEMENTATION
#include <stb_image.h>
#include <glad/glad.h>

namespace GlDrawStuff {

/**
 * @brief Represents an OpenGL 2D texture.
 *
 * Texture loads image data from an in memory encoded image using stb_image
 * and uploads it to an OpenGL 2D texture.
 *
 * The image is decoded from the supplied byte buffer and vertically flipped
 * before being uploaded. Texture wrapping is configured to GL_REPEAT.
 */
class Texture {
public:
    /**
     * @brief OpenGL texture object identifier.
     *
     * This value is generated by OpenGL when the Texture is constructed.
     */
    unsigned int texture;
    
    /**
     * @brief Creates an OpenGL texture from encoded image data.
     *
     * The supplied image data is decoded using stb_image and uploaded to
     * an OpenGL 2D texture. Supported image formats are 1, 3, and 4
     * channel images, corresponding to GL_RED, GL_RGB, and GL_RGBA.
     *
     * Texture coordinates are vertically flipped when the image is loaded.
     * Texture wrapping is configured to GL_REPEAT.
     *
     * @param texture_bytes Pointer to the encoded image data in memory.
     * @param texture_len Size of the encoded image data in bytes.
     * @param min_filter Minification filter used when sampling the texture.
     * @param mag_filter Magnification filter used when sampling the texture.
     *
     * @note If the image cannot be loaded or has an unsupported number of
     *       channels, the texture is left without uploaded image data and
     *       an error is printed to stdout.
     */
    Texture(const unsigned char* texture_bytes, int texture_len, GLint min_filter = GL_NEAREST_MIPMAP_NEAREST, GLint mag_filter = GL_NEAREST) {
        glGenTextures(1, &texture);
        glBindTexture(GL_TEXTURE_2D, texture);

        glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_REPEAT);
        glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_REPEAT);

        glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, min_filter);
        glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, mag_filter);

        int width, height, nr_channels;

        stbi_set_flip_vertically_on_load(true);

        unsigned char* data = stbi_load_from_memory(
            texture_bytes,
            texture_len,
            &width,
            &height,
            &nr_channels,
            0
        );

        if (data) {
            GLenum format;

            if (nr_channels == 1)
                format = GL_RED;
            else if (nr_channels == 3)
                format = GL_RGB;
            else if (nr_channels == 4)
                format = GL_RGBA;
            else {
                std::cout << "Unsupported number of channels: "
                          << nr_channels << '\n';

                stbi_image_free(data);
                glBindTexture(GL_TEXTURE_2D, 0);
                return;
            }

            glTexImage2D(
                GL_TEXTURE_2D,
                0,
                format,
                width,
                height,
                0,
                format,
                GL_UNSIGNED_BYTE,
                data
            );

            glGenerateMipmap(GL_TEXTURE_2D);
        }
        else {
            std::cout << "Failed to load texture: "
                      << stbi_failure_reason() << '\n';
        }

        stbi_image_free(data);

        glBindTexture(GL_TEXTURE_2D, 0);
    }
};

}


#endif // !GL_DRAW_STUFF_TEXTURE_HPP

